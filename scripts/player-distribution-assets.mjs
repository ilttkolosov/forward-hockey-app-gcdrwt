import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { unzipSync } from 'fflate';

const dir = fileURLToPath(new URL('../assets/player-distribution/', import.meta.url));
const repositoryArchiveDir = fileURLToPath(new URL('../assets/player-photos/', import.meta.url));
const archiveName = 'players-distribution.zip';
const archivePath = path.join(dir, archiveName);
const generatedPath = path.join(dir, 'bundled.ts');
const digest = bytes => crypto.createHash('sha256').update(bytes).digest('hex');

function verifyArchive(zip) {
  const files = unzipSync(zip);
  if (!files['manifest.json']) throw new Error('В ZIP дистрибутива отсутствует manifest.json');
  const manifest = JSON.parse(Buffer.from(files['manifest.json']).toString('utf8'));
  if (manifest.schema_version !== 1 || !Number.isSafeInteger(manifest.players_version) || manifest.players_version < 1
    || !Number.isFinite(Date.parse(manifest.generated_at)) || !Array.isArray(manifest.players) || !manifest.players.length
    || !Array.isArray(manifest.active_player_ids)) {
    throw new Error('Некорректный манифест архива игроков');
  }
  const ids = new Set();
  const expected = new Set(['manifest.json']);
  for (const player of manifest.players) {
    if (!Number.isSafeInteger(player.id) || player.id < 1 || ids.has(player.id) || typeof player.name !== 'string' || !player.name.trim()) {
      throw new Error('В архиве найдена некорректная или повторная карточка игрока');
    }
    ids.add(player.id);
    if (player.photo_file === null) continue;
    if (!new RegExp(`^player_${player.id}\\.(jpg|jpeg|png|webp)$`).test(player.photo_file) || !files[player.photo_file]?.length) {
      throw new Error(`Отсутствует фотография из манифеста для игрока ${player.id}`);
    }
    expected.add(player.photo_file);
  }
  if (manifest.active_player_ids.some(id => !ids.has(id)) || new Set(manifest.active_player_ids).size !== manifest.active_player_ids.length
    || Object.keys(files).some(name => !expected.has(name))) {
    throw new Error('Состав или фотографии архива не совпали с манифестом');
  }
  return { players: ids.size, current: manifest.active_player_ids.length, photos: expected.size - 1, version: manifest.players_version };
}

async function generate(sha256, modulePath = `./${archiveName}`) {
  const asset = sha256 ? `require(${JSON.stringify(modulePath)})` : 'null';
  const content = `// Generated by scripts/player-distribution-assets.mjs.\nexport const playerDistributionAsset: number | null = ${asset};\nexport const playerDistributionDigest: string | null = ${JSON.stringify(sha256)};\n`;
  const previous = await fs.readFile(generatedPath, 'utf8').catch(error => {
    if (error.code !== 'ENOENT') throw error;
  });
  if (previous === content) return;

  const temporary = `${generatedPath}.${process.pid}.tmp`;
  try {
    await fs.writeFile(temporary, content);
    await fs.rename(temporary, generatedPath);
  } finally {
    await fs.rm(temporary, { force: true });
  }
}

async function importArchive(file) {
  const zip = await fs.readFile(file);
  const summary = verifyArchive(zip);
  await fs.writeFile(archivePath, zip);
  await generate(digest(zip));
  console.log('[Игроки] Архив для установщика подготовлен', summary);
}

async function restore() {
  const releases = (await fs.readdir(repositoryArchiveDir, { withFileTypes: true })).flatMap(entry => {
    const match = entry.isFile() && /^players_distribution_v([1-9]\d*)\.zip$/.exec(entry.name);
    return match ? [{ name: entry.name, version: Number(match[1]) }] : [];
  });
  releases.sort((a, b) => b.version - a.version);
  const release = releases[0];
  if (release) {
    const zip = await fs.readFile(path.join(repositoryArchiveDir, release.name));
    const summary = verifyArchive(zip);
    if (summary.version !== release.version) {
      throw new Error(`Версия в манифесте ${release.name} не соответствует имени архива`);
    }
    await generate(digest(zip), `../player-photos/${release.name}`);
    console.log(`[Игроки] В сборку выбран ${release.name}: ${summary.players} игроков, ${summary.photos} фото`);
    return;
  }

  let zip;
  try {
    zip = await fs.readFile(archivePath);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    if (process.env.EAS_BUILD_PROFILE === 'production') {
      throw new Error('Для production-сборки добавьте архив players_distribution_vN.zip в assets/player-photos или укажите FORWARD_PLAYER_DISTRIBUTION_ZIP');
    }
    await generate(null);
    console.log('[Игроки] Полный архив для установщика пока отсутствует');
    return;
  }
  verifyArchive(zip);
  await generate(digest(zip));
}

const [command = 'restore', input] = process.argv.slice(2);
await fs.mkdir(dir, { recursive: true });
if (command === 'import' && input) await importArchive(input);
else if (command === 'restore' && process.env.FORWARD_PLAYER_DISTRIBUTION_ZIP) await importArchive(process.env.FORWARD_PLAYER_DISTRIBUTION_ZIP);
else if (command === 'restore') await restore();
else throw new Error('Использование: player-distribution-assets.mjs import <архив.zip> или restore');
