const fs = require("node:fs");
const path = require("node:path");
const {
  withAppBuildGradle,
  withDangerousMod,
} = require("expo/config-plugins");

const EXPECTED_ANDROID_PACKAGE = "com.kolosovaleksandr.Forward2014";
const GRADLE_MARKER = "// @generated by withAndroidFirebaseGuard";

function packageNamesFromGoogleServices(payload) {
  if (!payload || !Array.isArray(payload.client)) return [];
  return payload.client
    .map(
      (client) =>
        client &&
        client.client_info &&
        client.client_info.android_client_info &&
        client.client_info.android_client_info.package_name,
    )
    .filter((value) => typeof value === "string" && value.length > 0);
}

function validateGoogleServicesFile(
  filePath,
  expectedPackage = EXPECTED_ANDROID_PACKAGE,
) {
  if (!filePath) {
    throw new Error(
      "[Firebase] Android build is blocked: google-services.json is not configured. " +
        "Put google-services.json in the project root or provide GOOGLE_SERVICES_JSON.",
    );
  }

  if (!fs.existsSync(filePath)) {
    throw new Error(
      `[Firebase] Android build is blocked: google-services.json was not found at ${filePath}.`,
    );
  }

  let payload;
  try {
    payload = JSON.parse(fs.readFileSync(filePath, "utf8"));
  } catch (error) {
    throw new Error(
      `[Firebase] Android build is blocked: google-services.json is not valid JSON (${error instanceof Error ? error.message : String(error)}).`,
    );
  }

  const packageNames = packageNamesFromGoogleServices(payload);
  if (!packageNames.includes(expectedPackage)) {
    const found = packageNames.length ? packageNames.join(", ") : "none";
    throw new Error(
      `[Firebase] Android build is blocked: google-services.json does not contain package ${expectedPackage}. Found: ${found}.`,
    );
  }

  return { filePath, packageNames };
}

function resolveGoogleServicesPath(projectRoot, configuredPath) {
  if (!configuredPath) return null;
  return path.isAbsolute(configuredPath)
    ? configuredPath
    : path.resolve(projectRoot, configuredPath);
}

function gradleGuardBlock(expectedPackage = EXPECTED_ANDROID_PACKAGE) {
  return `
${GRADLE_MARKER}
def forwardExpectedFirebasePackage = "${expectedPackage}"
def forwardVerifyGoogleServicesJson = tasks.register("verifyForwardGoogleServicesJson") {
    doLast {
        def googleServicesFile = file("google-services.json")
        if (!googleServicesFile.exists()) {
            throw new GradleException(
                "[Firebase] Android build is blocked: android/app/google-services.json is missing. " +
                "Run Expo prebuild with the project-root google-services.json present."
            )
        }

        def googleServices = new groovy.json.JsonSlurper().parse(googleServicesFile)
        def packageNames = (googleServices.client ?: [])
            .collect { client -> client?.client_info?.android_client_info?.package_name }
            .findAll { packageName -> packageName != null }

        if (!packageNames.contains(forwardExpectedFirebasePackage)) {
            throw new GradleException(
                "[Firebase] Android build is blocked: google-services.json is for " +
                packageNames.join(", ") + ", expected " + forwardExpectedFirebasePackage + "."
            )
        }
    }
}

tasks.configureEach { task ->
    if (task.name == "preBuild") {
        task.dependsOn(forwardVerifyGoogleServicesJson)
    }
}
`;
}

module.exports = function withAndroidFirebaseGuard(config) {
  let nextConfig = withDangerousMod(config, [
    "android",
    async (modConfig) => {
      const configuredPath = modConfig.android?.googleServicesFile;
      const sourcePath = resolveGoogleServicesPath(
        modConfig.modRequest.projectRoot,
        configuredPath,
      );
      validateGoogleServicesFile(sourcePath);
      return modConfig;
    },
  ]);

  nextConfig = withAppBuildGradle(nextConfig, (modConfig) => {
    if (modConfig.modResults.language !== "groovy") {
      throw new Error(
        "[Firebase] Android build is blocked: unsupported app Gradle format for Firebase guard.",
      );
    }

    const contents = modConfig.modResults.contents;
    if (!contents.includes(GRADLE_MARKER)) {
      modConfig.modResults.contents =
        contents.trimEnd() + "\n" + gradleGuardBlock();
    }
    return modConfig;
  });

  return nextConfig;
};

module.exports.EXPECTED_ANDROID_PACKAGE = EXPECTED_ANDROID_PACKAGE;
module.exports.packageNamesFromGoogleServices = packageNamesFromGoogleServices;
module.exports.validateGoogleServicesFile = validateGoogleServicesFile;
module.exports.resolveGoogleServicesPath = resolveGoogleServicesPath;
module.exports.gradleGuardBlock = gradleGuardBlock;
