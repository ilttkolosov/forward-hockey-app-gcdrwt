const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const session = read("services/messengerSession.ts");
const api = read("services/messengerApi.ts");
const auth = read("contexts/MessengerAuthContext.tsx");
const register = read("app/messenger/register.tsx");
assert.match(session, /SESSION_RECOVERY_KEY/);
assert.match(session, /SESSION_PRESENT_KEY/);
assert.match(session, /hasMessengerSessionMarker/);
assert.match(api, /requestMessengerRefresh/);
assert.match(api, /auth\.refresh\.legacy_fallback/);
assert.match(api, /TERMINAL_REFRESH_ERROR_CODES/);
assert.doesNotMatch(api, /if \(error\.status === 401\) await clearMessengerSession/);
assert.match(auth, /hasMessengerSessionMarker/);
assert.match(register, /authStatus === "loading"/);
console.log("Messenger persistent-session checks passed.");
